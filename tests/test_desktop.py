"""
ЛАБОРАТОРНАЯ РАБОТА 6. ТЕСТИРОВАНИЕ ПО ТИПУ ПРИЛОЖЕНИЙ
Тип: Десктоп-приложение (консольное приложение, запускаемое на ПК)

Приложение «Расчёт стоимости поездки» реализовано как консольное
десктоп-приложение — оно запускается непосредственно на компьютере
пользователя как отдельный процесс операционной системы, без браузера
и без мобильной платформы.

Тестирование десктоп-приложений имеет свою специфику по сравнению с
веб- и мобильным тестированием. Проверяются, в частности:
    1. Корректность кодов возврата процесса (exit code) — по ним
       операционная система и другие программы понимают, успешно ли
       завершилось приложение.
    2. Независимость работы приложения от текущей рабочей директории
       (desktop-приложение может быть запущено из любого места —
       с ярлыка на рабочем столе, из проводника, из любой папки).
    3. Корректная кодировка вывода в консоль (особенно важно для
       приложений с русскоязычным интерфейсом на разных системах).
    4. Устойчивость к нестандартному завершению потока ввода
       (пользователь может закрыть терминал или прервать ввод).
"""

import subprocess
import sys
import os
import tempfile

APP_DIR = os.path.join(os.path.dirname(__file__), "..")
CLI_PATH = os.path.join(APP_DIR, "cli.py")


def run_app(user_input, cwd=APP_DIR):
    """Вспомогательная функция: запускает cli.py как отдельный процесс ОС,
    как это делает пользователь десктоп-приложения."""
    return subprocess.run(
        [sys.executable, CLI_PATH],
        input=user_input,
        capture_output=True,
        text=True,
        cwd=cwd,
        timeout=10,
    )


# ---------------------------------------------------------------------------
# ПРОВЕРКА 1: корректный код возврата при успешном завершении
# ---------------------------------------------------------------------------

def test_desktop01_exit_code_zero_on_success():
    """
    Десктоп-приложение при успешном завершении обязано вернуть
    операционной системе код возврата 0 — это стандарт, на который
    ориентируются скрипты автозапуска, батники и другие программы.
    """
    process = run_app("7.5\n55\n300\n1\nn\n")
    assert process.returncode == 0


# ---------------------------------------------------------------------------
# ПРОВЕРКА 2: приложение работает независимо от текущей рабочей директории
# ---------------------------------------------------------------------------

def test_desktop02_works_independent_of_working_directory():
    """
    Desktop-приложение может быть запущено пользователем из любого
    места (ярлык на рабочем столе, случайная папка через проводник),
    поэтому его результат не должен зависеть от того, из какой
    директории оно было запущено.
    """
    result_from_app_dir = run_app("7.5\n55\n300\n1\nn\n", cwd=APP_DIR)
    result_from_tmp_dir = run_app("7.5\n55\n300\n1\nn\n", cwd=tempfile.gettempdir())

    assert result_from_app_dir.returncode == 0
    assert result_from_tmp_dir.returncode == 0
    assert "1237.50" in result_from_app_dir.stdout
    assert "1237.50" in result_from_tmp_dir.stdout


# ---------------------------------------------------------------------------
# ПРОВЕРКА 3: корректная кодировка вывода (кириллица отображается верно)
# ---------------------------------------------------------------------------

def test_desktop03_output_encoding_is_utf8_and_readable():
    """
    Приложение ориентировано на русскоязычного пользователя, поэтому
    критически важно, чтобы весь текстовый интерфейс (подписи полей,
    результаты) корректно отображался в кодировке UTF-8, без «кракозябр».
    """
    process = run_app("7.5\n55\n300\n1\nn\n")

    # Проверяем, что ключевые русскоязычные фразы присутствуют
    # в неповреждённом виде (если бы была проблема с кодировкой,
    # эти строки просто не совпали бы или вызвали бы исключение раньше).
    assert "Расчёт стоимости поездки" in process.stdout
    assert "Общая стоимость поездки" in process.stdout
    assert "руб" in process.stdout


# ---------------------------------------------------------------------------
# ПРОВЕРКА 4: обработка ошибок валидации не приводит к падению процесса
# ---------------------------------------------------------------------------

def test_desktop04_validation_error_does_not_crash_process():
    """
    При некорректных пользовательских данных десктоп-приложение должно
    показать понятную ошибку и завершиться штатно, а не «упасть» с
    трудночитаемым traceback — это стандарт качества для десктоп-ПО.
    """
    process = run_app("7.5\n55\n-100\n1\nn\n")

    assert process.returncode == 0
    assert "Traceback" not in process.stderr
    assert "Ошибка ввода" in process.stdout


# ---------------------------------------------------------------------------
# ПРОВЕРКА 5 (НАЙДЕННЫЙ ДЕФЕКТ): неожиданное закрытие потока ввода
# ---------------------------------------------------------------------------

def test_desktop05_unexpected_input_stream_close_reveals_bug():
    """
    ОБНАРУЖЕННЫЙ ДЕФЕКT.

    Сценарий: пользователь неожиданно закрывает поток ввода — например,
    закрывает окно терминала или нажимает Ctrl+D (Linux/macOS) /
    Ctrl+Z (Windows) прямо во время ввода данных.

    Ожидаемое поведение (по стандартам качества десктоп-ПО): приложение
    должно перехватить эту ситуацию и корректно завершиться с понятным
    сообщением, не показывая пользователю трудночитаемый traceback Python.

    Фактическое поведение: приложение падает с необработанным
    исключением EOFError и кодом возврата 1, выводя полный traceback
    в stderr. Это является дефектом, который следует исправить —
    обернуть чтение ввода в обработку EOFError (и KeyboardInterrupt
    для Ctrl+C) с выводом дружелюбного сообщения о выходе.
    """
    process = run_app("")  # пустой ввод имитирует немедленное закрытие потока

    # Документируем фактическое (дефектное) поведение, чтобы тест
    # зафиксировал регрессию, если дефект будет исправлен в будущем —
    # тогда этот тест придётся обновить вместе с исправлением.
    assert process.returncode == 1
    assert "EOFError" in process.stderr
    assert "Traceback" in process.stderr
