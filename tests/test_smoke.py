"""
ЛАБОРАТОРНАЯ РАБОТА 3. ФУНКЦИОНАЛЬНОЕ ТЕСТИРОВАНИЕ
Вид: Smoke-тестирование (дымовое тестирование)

Принцип smoke-тестирования: это самая быстрая и поверхностная проверка,
цель которой — убедиться, что после сборки (или изменения кода) приложение
в принципе запускается и его КЛЮЧЕВЫЕ функции работают. Smoke-тест НЕ
проверяет все возможные случаи и граничные значения (это делается в других
видах тестирования, например в unit-тестах) — он лишь отвечает на вопрос:
"Не развалилось ли всё окончательно?"

Название пришло из электроники: если после сборки платы включить питание
и пошёл дым — тестировать дальше нет смысла, сборка сломана.

Smoke-тест обычно проверяет:
    1. Приложение запускается без ошибок импорта/синтаксиса.
    2. Ключевые компоненты создаются без падения программы.
    3. Основной, самый частый сценарий использования отрабатывает
       от начала до конца и даёт какой-то осмысленный результат
       (без проверки его точного значения — это не задача smoke-теста).
"""

import subprocess
import sys
import os

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

APP_DIR = os.path.join(os.path.dirname(__file__), "..")


# ---------------------------------------------------------------------------
# SMOKE-ПРОВЕРКА 1: модули приложения вообще импортируются без ошибок
# ---------------------------------------------------------------------------

def test_smoke01_modules_import_without_errors():
    """
    Критически важная проверка: если хотя бы один модуль содержит
    синтаксическую ошибку или ошибку на уровне импорта — вся программа
    неработоспособна. Дальнейшее тестирование не имеет смысла.
    """
    import vehicle
    import trip
    import calculator
    assert vehicle and trip and calculator


# ---------------------------------------------------------------------------
# SMOKE-ПРОВЕРКА 2: ключевые объекты создаются без падения программы
# ---------------------------------------------------------------------------

def test_smoke02_key_objects_can_be_created():
    """
    Проверяем, что основные классы приложения (Vehicle, Trip,
    TripCostCalculator) в принципе можно создать с разумными данными,
    не вдаваясь в детали всех возможных вариантов ввода.
    """
    from vehicle import Vehicle
    from trip import Trip
    from calculator import TripCostCalculator

    vehicle_obj = Vehicle(7.5, 55)
    trip_obj = Trip(300, 1)
    calc = TripCostCalculator(vehicle_obj, trip_obj)

    assert vehicle_obj is not None
    assert trip_obj is not None
    assert calc is not None


# ---------------------------------------------------------------------------
# SMOKE-ПРОВЕРКА 3: основной сценарий даёт результат (без проверки значения)
# ---------------------------------------------------------------------------

def test_smoke03_main_scenario_produces_a_result():
    """
    Проверяем, что типовой сценарий расчёта стоимости поездки
    выполняется от начала до конца и возвращает число, а не падает
    с исключением и не возвращает пустоту/None.
    """
    from vehicle import Vehicle
    from trip import Trip
    from calculator import TripCostCalculator

    calc = TripCostCalculator(Vehicle(7.5, 55), Trip(300, 2, extra_costs=[100]))

    result = calc.total_cost()

    assert result is not None
    assert isinstance(result, (int, float))
    assert result > 0


# ---------------------------------------------------------------------------
# SMOKE-ПРОВЕРКА 4: консольное приложение (cli.py) запускается и завершается
# ---------------------------------------------------------------------------

def test_smoke04_cli_runs_end_to_end_without_crash():
    """
    Самая важная smoke-проверка: запускаем реальное приложение так,
    как его запустит пользователь (через консоль), подаём типовые
    данные и убеждаемся, что процесс завершился без падения (код
    возврата 0) и напечатал итоговый результат.
    """
    user_input = "7.5\n55\n300\n1\nn\n"

    process = subprocess.run(
        [sys.executable, "cli.py"],
        input=user_input,
        capture_output=True,
        text=True,
        cwd=APP_DIR,
        timeout=10,
    )

    assert process.returncode == 0
    assert "Общая стоимость поездки" in process.stdout


# ---------------------------------------------------------------------------
# SMOKE-ПРОВЕРКА 5: приложение не падает молча на пустом вводе доп. расходов
# ---------------------------------------------------------------------------

def test_smoke05_cli_handles_zero_extra_costs_case():
    """
    Проверяем ещё один частый путь использования — пользователь сразу
    отказывается от добавления доп. расходов. Программа должна
    завершиться штатно.
    """
    user_input = "10\n50\n150\n2\nn\n"

    process = subprocess.run(
        [sys.executable, "cli.py"],
        input=user_input,
        capture_output=True,
        text=True,
        cwd=APP_DIR,
        timeout=10,
    )

    assert process.returncode == 0
    assert "Ошибка" not in process.stdout.split("---")[-1]
